# 3b. Document and history search
# --------------------------------------------------------------------------------------
def _machine_filter(q: Query) -> str | None:
    return q.machines[0] if len(q.machines) == 1 else None


def find_sources(retriever: Retriever, q: Query, method: str = "hybrid") -> list[tuple[Chunk, float]]:
    query = q.text + (" " + " ".join(q.alarms) if q.alarms else "")
    machine = _machine_filter(q)
    out: list[tuple[Chunk, float]] = []
    if q.wants_docs:
        hits = retriever.search(query, k=3, method=method, machine=machine, types={"manual", "sop"})
        out += _keep_relevant(hits)
    if q.wants_history or (q.wants_docs and (q.machines or q.alarms)):
        hits = retriever.search(query, k=60 if q.wants_recent else 3, method=method, machine=machine,
                                types={"work_order"})
        hits = _keep_relevant(hits)
        if q.wants_recent and hits:
            top = max(s for _, s in hits)
            hits = sorted([h for h in hits if h[1] >= 0.6 * top], key=lambda h: h[0].date, reverse=True)
        if q.period:
            in_period = [h for h in hits if q.period.start <= date.fromisoformat(h[0].date) <= q.period.end]
            hits = in_period or hits
        out += hits[: 3 if q.wants_history else 2]
    return out


def _keep_relevant(hits: list[tuple[Chunk, float]], share: float = 0.4) -> list[tuple[Chunk, float]]:
    if not hits:
        return hits
    top = hits[0][1]
    return [h for h in hits if h[1] >= share * top and h[1] > 0]


