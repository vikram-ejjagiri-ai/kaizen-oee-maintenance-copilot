# 4. Answer
# --------------------------------------------------------------------------------------
SYSTEM_PROMPT = """You are the maintenance copilot of a metal-parts plant. You help technicians,
shift leaders and production managers. Follow these rules strictly:
1. Use ONLY the KPI facts and the numbered sources below. Cite every statement with [KPI] or [S1], [S2], ...
2. Use only numbers that appear in the KPI facts or sources. Never estimate or invent numbers.
3. If the material does not answer the question, say so clearly and suggest who to ask.
4. Never explain how to bypass, bridge, mute or disable safety devices. For hands-on repair steps,
   remind the reader to apply lockout/tagout (SOP-LOTO).
5. Start with a short direct answer (1-2 sentences), then at most 5 bullet points.
   Plain English for shop-floor staff. No preamble."""

REPAIR_WORDS = re.compile(r"\b(fix|repair|replac|check|troubleshoot|clean|open|remove|change)\w*", re.I)


@dataclass
class Answer:
    question: str
    text: str
    mode: str
    query: Query
    sources: list[tuple[Chunk, float]] = field(default_factory=list)
    kpi: dict | None = None
    flags: list[str] = field(default_factory=list)


class Copilot:
    def __init__(self, tables: dict, facts: pd.DataFrame, retriever: Retriever,
                 llm_model: str | None = config.LLM_MODEL, use_llm: bool = True):
        self.t, self.facts, self.retriever = tables, facts, retriever
        models = ollama_models() if use_llm else None
        self.llm = llm_model if use_llm and model_available(llm_model, models) else None
        self.retrieval_method = "hybrid" if retriever.has_dense else "bm25"

    @property
    def mode(self) -> str:
        return f"LLM ({self.llm}, local via Ollama)" if self.llm else "Fallback (no LLM: facts and passages only)"

    def ask(self, question: str) -> Answer:
        q = parse(question)

        if is_safety_bypass(question):
            safe = parse(re.sub(BYPASS, "fault", question.lower()))
            safe.wants_docs, safe.wants_history = True, False
            srcs = find_sources(self.retriever, safe, self.retrieval_method)
            loto = [c for c in self.retriever.chunks if c.chunk_id == "SOP-LOTO#safety-devices-are-never-bypassed"]
            srcs = [(c, 0.0) for c in loto] + [s for s in srcs if s[0].chunk_id not in {c.chunk_id for c in loto}][:2]
            text = ("I can't help with bypassing, bridging or disabling a safety device. A faulty safety "
                    "device means the machine stays stopped until it is repaired and tested by qualified "
                    "personnel [S1]. Call maintenance and your shift leader.\n\n"
                    "What you *can* do safely is follow the troubleshooting steps for the fault:\n"
                    + "\n".join(f"- {_best_passage(c, question)} [S{i}]" for i, (c, _) in enumerate(srcs[1:], 2)))
            return Answer(question, text, "Guardrail (safety)", q, srcs, None, ["safety_refusal"])

        kpi = kpi_tool(self.t, self.facts, q) if q.wants_kpi else None
        search_q = q
        if kpi and q.wants_docs and WHY_WORDS.search(q.text.lower()) and kpi["tables"].get("pareto") is not None:
            # "Why was OEE low?": let the numbers steer the document search. The biggest
            # downtime reasons and alarms of the period become search words.
            par = kpi["tables"]["pareto"].head(2)
            words = " ".join(par.description) + " " + " ".join(kpi.get("top_alarms", [])[:2])
            search_q = parse(q.text)
            search_q.text = f"{q.text} {words}"
            search_q.wants_history = search_q.wants_history or bool(q.period)
        sources = find_sources(self.retriever, search_q, self.retrieval_method) if (q.wants_docs or q.wants_history) else []

        confidence = best_bm25(self.retriever, q.text + " " + " ".join(q.alarms), _machine_filter(q))
        if not kpi and (not sources or confidence < config.MIN_BM25_SCORE):
            text = ("I couldn't find this in the plant data, manuals, SOPs or work orders. "
                    "Please ask the maintenance planner or shift leader. I can answer questions about "
                    "OEE and downtime, alarms, maintenance procedures and past repairs on CNC-01, "
                    "CNC-02, PRESS-01 and ASSY-01.")
            return Answer(question, text, "Not found", q, [], None, ["not_found"])

        if self.llm:
            try:
                text, flags = self._llm_answer(q, kpi, sources)
                return Answer(question, text, self.mode, q, sources, kpi, flags)
            except requests.RequestException as e:
                fallback_flag = [f"llm_error: {type(e).__name__}"]
        else:
            fallback_flag = []
        return Answer(question, self._template_answer(q, kpi, sources), "Fallback (no LLM)", q, sources, kpi,
                      fallback_flag)

    # ---- LLM path ----------------------------------------------------------------------
    def context(self, kpi: dict | None, sources: list[tuple[Chunk, float]]) -> str:
        parts = []
        if kpi:
            parts.append("KPI FACTS [KPI] (calculated from MES data):\n" + "\n".join(f"- {l}" for l in kpi["lines"]))
        for i, (c, _) in enumerate(sources, 1):
            parts.append(f"[S{i}] {c.title} - {c.section}" + (f" ({c.date})" if c.date else "") + f"\n{c.text}")
        return "\n\n".join(parts)

    def _llm_answer(self, q: Query, kpi, sources) -> tuple[str, list[str]]:
        ctx = self.context(kpi, sources)
        r = requests.post(f"{config.OLLAMA_URL}/api/chat", timeout=config.LLM_TIMEOUT_S, json={
            "model": self.llm, "stream": False,
            "options": {"temperature": 0.1, "num_ctx": 4096},
            "messages": [{"role": "system", "content": SYSTEM_PROMPT},
                         {"role": "user", "content": f"Question: {q.text}\n\n{ctx}"}],
        })
        r.raise_for_status()
        text = r.json()["message"]["content"].strip()
        return text, check_answer(text, ctx + " " + q.text)

    # ---- fallback path -----------------------------------------------------------------
    def _template_answer(self, q: Query, kpi, sources) -> str:
        out = []
        if kpi:
            out.append("**Plant data** [KPI]")
            out += [f"- {l}" for l in kpi["lines"]]
        if sources:
            out.append("\n**From the manuals and work orders**")
            for i, (c, _) in enumerate(sources, 1):
                out.append(f"- **{c.citation()}** [S{i}]: {_best_passage(c, q.text)}")
        if sources and REPAIR_WORDS.search(q.text):
            out.append("\nBefore any hands-on work: stop the machine and apply lockout/tagout (SOP-LOTO).")
        return "\n".join(out)


def _best_passage(c: Chunk, question: str, max_chars: int = 420) -> str:
    """Pick the sentences of a chunk that share the most words with the question."""
    if c.source_type == "work_order":
        return c.text[:max_chars]
    qt = set(tokenize(expand_query(question)))
    # undo line wrapping: a new line only starts a new item if it is a list item or bold label
    text = re.sub(r"\n(?!\s*(?:\d+\.|-|\*\*|\|))", " ", c.text)
    parts = [re.sub(r"\s+", " ", s).strip(" -*") for s in re.split(r"(?<=[.!?])\s+|\n", text)
             if len(s.strip()) > 3]
    scored = sorted(range(len(parts)), key=lambda i: -len(qt & set(tokenize(parts[i]))))
    keep, total = [], 0
    for i in scored:
        if total + len(parts[i]) > max_chars and keep:
            break
        keep.append(i)
        total += len(parts[i])
    return " ".join(parts[i] for i in sorted(keep)).replace("**", "")


# --------------------------------------------------------------------------------------
# 5. Answer checks
# --------------------------------------------------------------------------------------
NUM = re.compile(r"(?<![\w-])\d[\d,]*(?:\.\d+)?")


def _norm(n: str) -> str:
    return n.replace(",", "").rstrip(".")


def check_answer(text: str, context: str) -> list[str]:
    """Flags for the user: numbers not found in the facts, missing citations."""
    flags = []
    allowed = {_norm(n) for n in NUM.findall(context)}
    # 61.0 % and 61 % are the same number
    allowed |= {a[:-2] for a in allowed if a.endswith(".0")}
    unknown = sorted({_norm(n) for n in NUM.findall(text) if _norm(n) not in allowed
                      and not (n.isdigit() and int(n) <= 10)})
    if unknown:
        flags.append("unverified_numbers: " + ", ".join(unknown[:8]))
    if not re.search(r"\[(S\d+|KPI)\]", text):
        flags.append("no_citations")
    return flags
