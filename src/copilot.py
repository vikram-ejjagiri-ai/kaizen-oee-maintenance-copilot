# 3a. KPI tool
# --------------------------------------------------------------------------------------
def pct(x) -> str:
    return "n/a" if pd.isna(x) else f"{100 * x:.1f} %"


def kpi_tool(t: dict, facts: pd.DataFrame, q: Query) -> dict:
    """Calculate the KPIs the question needs. Returns text lines (for the LLM and the user)
    and tables (for the app)."""
    p = q.period or Period(facts.shift_date.min().date(), facts.shift_date.max().date(), "the whole data period")
    machines = q.machines or None
    f = oee.filter_facts(facts, p.start, p.end, machines, q.shifts or None)
    scope = f"{', '.join(q.machines) if q.machines else 'all machines'}" + (
        f", {', '.join(q.shifts)} shift" if q.shifts else "")
    lines = [f"Scope: {scope}, {p.label} ({p.start} to {p.end})."]
    tables: dict[str, pd.DataFrame] = {}
    if f.empty or f.ppt_min.sum() == 0:
        lines.append("No production data in this period (production runs Monday to Friday, "
                     f"data covers {facts.shift_date.min():%Y-%m-%d} to {facts.shift_date.max():%Y-%m-%d}).")
        return {"lines": lines, "tables": tables, "period": p}

    tot = oee.aggregate(f).iloc[0]
    lines.append(f"OEE {pct(tot.oee)} (availability {pct(tot.availability)}, performance "
                 f"{pct(tot.performance)}, quality {pct(tot.quality)}). Good parts {int(tot.good_count):,}, "
                 f"scrap {int(tot.scrap_count):,} ({pct(tot.scrap_rate)}). Unplanned downtime "
                 f"{int(tot.down_min):,} min of {int(tot.ppt_min):,} min planned production time.")

    # previous period of the same length, for context
    length = (p.end - p.start).days + 1
    prev = oee.filter_facts(facts, p.start - timedelta(days=length), p.start - timedelta(days=1),
                            machines, q.shifts or None)
    if not prev.empty and prev.ppt_min.sum() > 0 and length < 60:
        po = oee.aggregate(prev).iloc[0].oee
        lines.append(f"Previous {length} days: OEE {pct(po)} (change {100 * (tot.oee - po):+.1f} points).")

    if len(f.machine_id.unique()) > 1:
        bym = oee.aggregate(f, ["machine_id"]).sort_values("oee")
        tables["by_machine"] = bym
        lines.append("By machine: " + "; ".join(
            f"{r.machine_id} OEE {pct(r.oee)} (A {pct(r.availability)}, P {pct(r.performance)}, Q {pct(r.quality)})"
            for r in bym.itertuples()) + ".")
    if q.shifts or re.search(r"\bshifts?\b", q.text.lower()):
        f_all = oee.filter_facts(facts, p.start, p.end, machines)
        bys = oee.aggregate(f_all, ["shift"])
        tables["by_shift"] = bys
        lines.append("By shift: " + "; ".join(
            f"{r.shift} OEE {pct(r.oee)} (A {pct(r.availability)}, P {pct(r.performance)}, Q {pct(r.quality)})"
            for r in bys.itertuples()) + ".")
        lines.append("Changeovers by shift: " + "; ".join(
            f"{r.shift} {r.changeovers} changeovers, {r.minutes:,} min, average {r.avg_min:.0f} min"
            for r in setup_by_shift(t, p, machines).itertuples()) + ".")
    if length > 14:
        byw = oee.aggregate(f, ["week"])
        tables["by_week"] = byw
        lines.append("OEE by week: " + ", ".join(f"{r.week} {pct(r.oee)}" for r in byw.itertuples()) + ".")

    par = oee.downtime_pareto(t, p.start, p.end, machines, q.shifts or None).head(5)
    tables["pareto"] = par
    if not par.empty:
        lines.append("Top downtime reasons: " + "; ".join(
            f"{r.reason_code} ({r.description}) {int(r.minutes):,} min in {int(r.stops)} stops"
            for r in par.itertuples()) + ".")

    rel = oee.reliability(t, facts, p.start, p.end)
    if machines:
        rel = rel[rel.machine_id.isin(machines)]
    tables["reliability"] = rel
    lines.append("Failures: " + "; ".join(
        f"{r.machine_id} {int(r.failures)} failures, MTTR {r.mttr_min:.0f} min" if r.failures else f"{r.machine_id} no failures"
        for r in rel.itertuples()) + ".")

    top_alarms: list[str] = []
    al = t["alarms"]
    al = al[(al.ts >= pd.Timestamp(p.start)) & (al.ts < pd.Timestamp(p.end) + pd.Timedelta(days=1))]
    if machines:
        al = al[al.machine_id.isin(machines)]
    if not al.empty:
        top = al.groupby(["alarm_code", "message"]).size().sort_values(ascending=False).head(4)
        top_alarms = [c for c, _ in top.index]
        lines.append("Most frequent alarms: " + "; ".join(f"{c} {m} x{n}" for (c, m), n in top.items()) + ".")
    return {"lines": lines, "tables": tables, "period": p}


def setup_by_shift(t: dict, p: Period, machines: list[str] | None) -> pd.DataFrame:
    """Changeover count and average duration per shift. Setup segments interrupted only by a
    break are merged so one changeover counts once."""
    ev = t["events"]
    ev = ev[(ev.shift_date >= pd.Timestamp(p.start)) & (ev.shift_date <= pd.Timestamp(p.end))]
    if machines:
        ev = ev[ev.machine_id.isin(machines)]
    ev = ev[ev.state != "PLANNED_STOP"].sort_values(["machine_id", "start_ts"])
    new_block = ~((ev.reason_code == "SETUP") & (ev.reason_code.shift() == "SETUP")
                  & (ev.machine_id == ev.machine_id.shift()))
    ev = ev.assign(block=new_block.cumsum())
    s = ev[ev.reason_code == "SETUP"].groupby(["block", "shift"], as_index=False).duration_min.sum()
    s = s.groupby("shift", as_index=False).agg(changeovers=("duration_min", "size"),
                                                minutes=("duration_min", "sum"),
                                                avg_min=("duration_min", "mean"))
    return s


