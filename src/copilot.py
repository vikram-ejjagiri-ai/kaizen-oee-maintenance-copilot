"""Maintenance copilot: answers shop-floor questions from plant data and documents.

Pipeline for every question:
    1. Guardrail: refuse requests to bypass safety devices (still point to safe troubleshooting).
    2. Understand the question: machines, alarm codes, time period, shift, intent.
    3. Tools:
       - KPI tool: OEE engine on MES data (numbers are calculated, never generated by the LLM)
       - Document search: manuals and SOPs
       - History search: maintenance work orders (newest first for "last time" questions)
    4. Answer: a local LLM (Ollama) writes the answer from these facts with citations. Without
       Ollama, a template answer shows the same facts and best passages (fallback mode).
    5. Checks: every number in an LLM answer must appear in the facts; citations required.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import date, timedelta

import pandas as pd
import requests

from src import config, oee
from src.retrieval import Chunk, Retriever, best_bm25, expand_query, model_available, ollama_models, tokenize

# --------------------------------------------------------------------------------------
# 1. Guardrail
# --------------------------------------------------------------------------------------
BYPASS = re.compile(r"\b(bypass\w*|bridg\w*|jumper\w*|disabl\w*|mute|muting|overrid\w*|defeat\w*|"
                    r"deactivat\w*|tape over|cheat|trick|switch(?:ed|ing)? off|turn(?:ed|ing)? off|"
                    r"get around|work around|workaround|ignore)\b")
SAFETY_DEVICE = re.compile(r"\b(light curtain|curtain|interlock|e-?stop|emergency stop|two[- ]hand|"
                           r"safety (?:device|switch|sensor|door|guard)|door switch|guard)\b")


def is_safety_bypass(q: str) -> bool:
    q = q.lower()
    return bool(BYPASS.search(q) and SAFETY_DEVICE.search(q))


# --------------------------------------------------------------------------------------
# 2. Question understanding
# --------------------------------------------------------------------------------------
MONTHS = {m: i for i, m in enumerate(["january", "february", "march", "april", "may", "june", "july",
                                      "august", "september", "october", "november", "december"], 1)}
ALL_MACHINES = ["CNC-01", "CNC-02", "PRESS-01", "ASSY-01"]
KPI_WORDS = re.compile(r"\b(oee|availability|performance|quality|scrap\w*|downtime|down time|loss\w*|"
                       r"mtbf|mttr|pareto|worst|best|compare|comparison|trend|kpi|output|produced|"
                       r"how many|how much|how long|efficien\w*|biggest|longest|shortest|most|least|"
                       r"which (?:shift|machine)|average|top \d|reject\w*|minutes|hours)\b")
DOC_WORDS = re.compile(r"\b(how (?:do|to|can|should)|procedure|steps?|fix\w*|repair\w*|replac\w*|"
                       r"check\w*|troubleshoot\w*|alarm|mean\w*|cause\w*|what should|safety|lockout|"
                       r"loto|maintenance plan|last time|history|work orders?|happened|root cause|"
                       r"why|reduce|improve|prevent\w*|recommend\w*|plan|calculat\w*|defin\w*|"
                       r"explain\w*|benchmark\w*|world class)\b")
HISTORY_WORDS = re.compile(r"\b(parts used|were used|was done|did we|last time|previous\w*|before|history|work orders?|happened|"
                           r"fixed|repaired|recurring|again|how often|latest|recent\w*|root cause)\b")
DEFINITION_WORDS = re.compile(r"\b(calculat\w*|defin\w*|formula|benchmark\w*|world class|"
                              r"what (?:is|does) (?:oee|availability|performance|quality)\b|mean\w*)")
WHY_WORDS = re.compile(r"\b(why|cause\w*|reason\w*|explain\w*|happened|root cause|what went wrong)\b")
RECENCY_WORDS = re.compile(r"\b(last time|latest|most recent|recent\w*|last fix)\b")
ALARM = re.compile(r"\b([ahse])-?(\d{3})\b", re.I)


@dataclass
class Period:
    start: date
    end: date
    label: str


@dataclass
class Query:
    text: str
    machines: list[str]
    alarms: list[str]
    period: Period | None
    shifts: list[str]
    wants_kpi: bool
    wants_docs: bool
    wants_history: bool
    wants_recent: bool


def parse_machines(q: str) -> list[str]:
    q = q.lower()
    found = []
    for n in ("1", "2"):
        if re.search(rf"\bcnc[\s-]?0?{n}\b", q):
            found.append(f"CNC-0{n}")
    if not found and re.search(r"\b(cnc|lathes?|turning|tl-?400)\b", q):
        found += ["CNC-01", "CNC-02"]
    if re.search(r"\bpress(?:es)?\b|\bpress[\s-]?0?1\b|\bhp-?250\b", q):
        found.append("PRESS-01")
    if re.search(r"\bassy[\s-]?0?1\b|\bassembly\b|\bac-?30\b", q):
        found.append("ASSY-01")
    return found


def _week(year: int, week: int) -> Period:
    start = date.fromisocalendar(year, week, 1)
    return Period(start, start + timedelta(days=6), f"week {year}-W{week:02d}")


def _month(year: int, month: int) -> Period:
    start = date(year, month, 1)
    end = (date(year + (month == 12), month % 12 + 1, 1)) - timedelta(days=1)
    return Period(start, end, start.strftime("%B %Y"))


def parse_period(q: str, today: date = config.AS_OF_DATE) -> Period | None:
    q = q.lower()
    year = today.year
    monday = today - timedelta(days=today.weekday())
    if re.search(r"\b(last|previous) week\b", q):
        p = _week(*(monday - timedelta(days=7)).isocalendar()[:2])
        p.label = f"last week ({p.label})"
        return p
    if re.search(r"\bthis week\b", q):
        return Period(monday, today, f"this week (week {year}-W{today.isocalendar()[1]:02d})")
    if "yesterday" in q:
        d = today - timedelta(days=1)
        return Period(d, d, f"yesterday ({d})")
    if re.search(r"\btoday\b", q):
        return Period(today, today, f"today ({today})")
    if re.search(r"\b(last|previous) month\b", q):
        first = today.replace(day=1) - timedelta(days=1)
        return _month(first.year, first.month)
    if re.search(r"\bthis month\b", q):
        return Period(today.replace(day=1), today, f"this month ({today:%B %Y})")
    m = re.search(r"\b(?:last|past) (\d+) (day|week)s?\b", q)
    if m:
        days = int(m.group(1)) * (7 if m.group(2) == "week" else 1)
        return Period(today - timedelta(days=days - 1), today, f"last {m.group(1)} {m.group(2)}s")
    m = re.search(r"\b(?:week|kw|cw|w)\s?(\d{1,2})\b", q)
    if m and 1 <= int(m.group(1)) <= 53:
        return _week(year, int(m.group(1)))
    m = re.search(r"\b(\d{4})-(\d{2})-(\d{2})\b", q)
    if m:
        d = date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
        return Period(d, d, str(d))
    for name, num in MONTHS.items():
        m = re.search(rf"\b(\d{{1,2}})(?:st|nd|rd|th)?\s+{name}\b|\b{name}\s+(\d{{1,2}})(?:st|nd|rd|th)?\b", q)
        if m:
            d = date(year, num, int(m.group(1) or m.group(2)))
            return Period(d, d, str(d))
    for name, num in MONTHS.items():
        if re.search(rf"\b(end|late) of {name}\b", q):
            p = _month(year, num)
            return Period(p.end - timedelta(days=9), p.end, f"end of {p.label}")
        if re.search(rf"\b(start|beginning|early) of {name}\b", q):
            p = _month(year, num)
            return Period(p.start, p.start + timedelta(days=9), f"start of {p.label}")
        if re.search(rf"\b{name}\b", q):
            return _month(year, num)
    return None


def parse_shifts(q: str) -> list[str]:
    q = q.lower()
    out = []
    if re.search(r"\b(early|morning) shift", q):
        out.append("Early")
    if re.search(r"\b(late|afternoon) shift", q):
        out.append("Late")
    if re.search(r"\bnight", q):
        out.append("Night")
    return out


def parse(q: str) -> Query:
    low = q.lower()
    alarms = [f"{a.upper()}-{n}" for a, n in ALARM.findall(q)]
    period = parse_period(q)
    wants_kpi = bool(KPI_WORDS.search(low))
    wants_history = bool(HISTORY_WORDS.search(low))
    wants_docs = bool(DOC_WORDS.search(low) or alarms or not wants_kpi)
    machines = parse_machines(q)
    # "what happened at the end of July" -> also show the numbers for that period
    if period and wants_history and machines:
        wants_kpi = True
    # "How is OEE calculated?" is a definition question, not a request for plant numbers
    if DEFINITION_WORDS.search(low) and not machines and not period:
        wants_kpi, wants_docs = False, True
    return Query(q, parse_machines(q), alarms, period, parse_shifts(q), wants_kpi, wants_docs,
                 wants_history, bool(RECENCY_WORDS.search(low)))


